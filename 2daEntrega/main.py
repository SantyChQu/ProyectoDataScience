import matplotlib.pyplot as plt
import matplotlib.cm as cm
import numpy as np
import pandas as pd
from sklearn.preprocessing import OrdinalEncoder
from sklearn.metrics import silhouette_score, silhouette_samples, adjusted_rand_score

def metricas_particion(df_in, columnas, etiquetas):
    """Silueta de Hamming, % de siluetas negativas y tamaño del cluster mayoritario."""
    X_ord = OrdinalEncoder().fit_transform(df_in[columnas])
    ss = silhouette_samples(X_ord, etiquetas, metric="hamming")
    resumen = {
        "n": len(df_in),
        "Silueta_Hamming": ss.mean(),
        "Pct_Negativos": (ss < 0).mean() * 100,
        "Max_Cluster_%": pd.Series(etiquetas).value_counts(normalize=True).max() * 100,
    }
    return resumen, ss

def graficar_silueta(ss, etiquetas, titulo="Análisis de Silueta (Distancia de Hamming)"):
    """Genera el gráfico de silueta clásico a partir de los valores silhouette_samples."""
    etiquetas = np.asarray(etiquetas)
    clusters_unicos = np.sort(np.unique(etiquetas))
    n_clusters = len(clusters_unicos)
    silueta_media = ss.mean()

    fig, ax = plt.subplots(figsize=(9, 5.5))
    y_lower = 10

    for i, c in enumerate(clusters_unicos):
        # Extraer y ordenar los valores de silueta del cluster c
        valores_c = ss[etiquetas == c]
        valores_c.sort()

        tamano_c = valores_c.shape[0]
        y_upper = y_lower + tamano_c

        color = cm.nipy_spectral(float(i) / n_clusters)
        ax.fill_betweenx(
            np.arange(y_lower, y_upper),
            0,
            valores_c,
            facecolor=color,
            edgecolor=color,
            alpha=0.75,
        )

        # Etiqueta con el número de cluster y su tamaño en el eje Y
        ax.text(-0.04, y_lower + 0.5 * tamano_c, f"C{c}\n(n={tamano_c:,})", va="center", ha="right", fontsize=9)
        y_lower = y_upper + 10  # Espacio entre bloques de clusters

    # Línea vertical con el promedio global de silueta
    ax.axvline(x=silueta_media, color="red", linestyle="--", linewidth=1.5, label=f"Silueta media: {silueta_media:.4f}")
    ax.axvline(x=0, color="black", linestyle="-", linewidth=0.8, alpha=0.5)

    ax.set_title(titulo, fontsize=12, fontweight="bold")
    ax.set_xlabel("Coeficiente de Silueta (Hamming)")
    ax.set_ylabel("Registros agrupados por Cluster")
    ax.set_yticks([])  # Ocultamos ticks numéricos del eje Y porque mostramos las etiquetas de cluster
    ax.set_xlim([min(-0.2, ss.min() - 0.05), min(1.0, ss.max() + 0.05)])
    ax.legend(loc="lower right")
    ax.grid(axis="x", linestyle=":", alpha=0.5)

    plt.tight_layout()
    plt.show()

