def clasificar_contraparte(v):
    s = str(v).lower()
    if "automóvil" in s or "camioneta" in s:
        return "Auto / Camioneta"
    if any(x in s for x in ["camión", "colectivo", "micro", "tren"]):
        return "Vehículo pesado"
    if any(x in s for x in ["motocicleta", "ciclomotor", "bicicleta"]):
        return "Moto / Bici"
    return "Sin determinar"

