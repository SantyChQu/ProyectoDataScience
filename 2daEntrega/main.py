"""### 12.7 Auditoría con Boosting: ¿qué variables usa realmente cada partición?

Para cada partición entrenamos un `HistGradientBoostingClassifier` que intenta **predecir el cluster** a partir de las variables, y medimos la **importancia por permutación** de cada variable (cuánto empeora la predicción si se la "mezcla"). Una variable con importancia cercana a 0 casi no participa en la separación de los grupos.

Además de la importancia, el accuracy del clasificador indica qué tan "explicables" por las variables son los clusters.
"""

from sklearn.ensemble import HistGradientBoostingClassifier
from sklearn.inspection import permutation_importance
from sklearn.model_selection import train_test_split

def auditar(labels):
    X_tr, X_te, y_tr, y_te = train_test_split(X_ord, labels, test_size=0.25, random_state=42, stratify=labels)
    clf = HistGradientBoostingClassifier(categorical_features=list(range(len(variables_finales))), random_state=42).fit(X_tr, y_tr)
    perm = permutation_importance(clf, X_te, y_te, n_repeats=5, random_state=42)
    fila = {col: float(v) for col, v in zip(variables_finales, perm.importances_mean)}
    fila["Accuracy_test"] = clf.score(X_te, y_te)
    return fila

tabla_importancias = pd.DataFrame({nombre: auditar(lab) for nombre, lab in labels_bench.items()}).T
display(tabla_importancias.round(3))

