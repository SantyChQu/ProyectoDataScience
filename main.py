def clasificar_franja(hora):
    if pd.isna(hora):
        return "desconocida"
    elif 6 <= hora < 12:
        return "mañana"
    elif 12 <= hora < 18:
        return "tarde"
    elif 18 <= hora < 24:
        return "noche"
    else:
        return "madrugada"

df_modelo["franja_horaria"] = df_modelo["hora_hecho"].apply(clasificar_franja)

