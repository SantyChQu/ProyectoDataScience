"""Agrupar las categorías de siniestros en 5 grupos para reducir la cantidad de clases, facilitar la clasificación y mejorar la representación de las categorías menos frecuentes."""

import re
import unicodedata

def normalizar_texto(texto):
    texto = str(texto).strip().lower()
    texto = unicodedata.normalize("NFD", texto)
    texto = "".join(
        c for c in texto if unicodedata.category(c) != "Mn"
    )
    texto = re.sub(r"\s+", " ", texto)
    return texto

def asignar_grupo(tipo):
    t = normalizar_texto(tipo)

    # Grupo 1: colisiones entre vehículos y colisiones múltiples
    if "multiple" in t or re.search(
        r"vehiculo\s*[-–]\s*vehiculo", t
    ):
        return "Grupo 1"

    # Grupo 2: colisión vehículo-persona
    if re.search(r"vehiculo\s*[-–]\s*persona", t):
        return "Grupo 2"

    # Grupo 3: vuelcos, despistes y derrapes
    if any(palabra in t for palabra in [
        "vuelco", "despiste", "derrape"
    ]):
        return "Grupo 3"

    # Grupo 4: colisiones con animales, objetos,
    # tracción a sangre o vehículos estacionados
    if any(palabra in t for palabra in [
        "animal", "objeto", "traccion a sangre",
        "vehiculo estacionado"
    ]):
        return "Grupo 4"

    # Grupo 5: todas las categorías restantes
    return "Grupo 5"

