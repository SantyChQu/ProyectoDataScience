"""Las tres variables predictoras son categóricas, por eso utilizaremos One-Hot Encoding, que transforma cada categoría en una columna binaria.

También separamos los datos en entrenamiento (80 %) y prueba (20 %). La división será estratificada para conservar, en lo posible, la proporción de cada grupo en ambos conjuntos.
"""

# Codificamos las variables categóricas
from sklearn.compose import ColumnTransformer
from sklearn.preprocessing import OneHotEncoder
from sklearn.pipeline import Pipeline

preprocesador = ColumnTransformer(
    transformers=[
        (
            "categoricas",
            OneHotEncoder(handle_unknown="ignore"),
            ["franja_horaria", "tipo_lugar", "clima_condicion"]
        )
    ],
    remainder="drop"
)

# Definimos los modelos
from sklearn.linear_model import LogisticRegression
from sklearn.tree import DecisionTreeClassifier
from sklearn.ensemble import RandomForestClassifier

modelos = {
    "Regresión Logística": LogisticRegression(
        max_iter=2000,
        class_weight="balanced",
        random_state=42
    ),

    "Árbol de Decisión": DecisionTreeClassifier(
        class_weight="balanced",
        random_state=42
    ),

    "Random Forest": RandomForestClassifier(
        n_estimators=200,
        class_weight="balanced",
        random_state=42,
        n_jobs=-1
    )
}

"""Entrenar y evaluar los modelos

Vamos a utilizar las mismas métricas y los mismos datos de prueba para los tres modelos.
"""

from sklearn.metrics import (
    accuracy_score,
    balanced_accuracy_score,
    f1_score,
    classification_report,
    confusion_matrix
)

import time

resultados = []
modelos_entrenados = {}
predicciones = {}

for nombre, modelo in modelos.items():

    pipeline = Pipeline([
        ("preprocesador", preprocesador),
        ("modelo", modelo)
    ])

    inicio = time.time()

    pipeline.fit(X_train, y_train)
    y_pred = pipeline.predict(X_test)

    tiempo = time.time() - inicio

    modelos_entrenados[nombre] = pipeline
    predicciones[nombre] = y_pred

    resultados.append({
        "Modelo": nombre,
        "Accuracy": accuracy_score(y_test, y_pred),
        "Balanced accuracy": balanced_accuracy_score(y_test, y_pred),
        "F1 macro": f1_score(
            y_test, y_pred, average="macro", zero_division=0
        ),
        "Tiempo (s)": round(tiempo, 2)
    })

    print(f"\n{'=' * 55}")
    print(nombre)
    print(f"{'=' * 55}")
    print(classification_report(
        y_test,
        y_pred,
        labels=sorted(y.unique()),
        zero_division=0
    ))

comparacion = pd.DataFrame(resultados).sort_values(
    "Balanced accuracy", ascending=False
).reset_index(drop=True)

