"""# **Aprendizaje Supervisado**
*¿Qué tipo de siniestro podemos esperar según clima, hora/franja horaria, lugar y provincia?*
"""

# Variable objetivo (y)
y = df_modelo["modo_produccion_hecho_ampliada"]

# Variables predictoras (X)
X = df_modelo[
    ["clima_condicion", "franja_horaria", "tipo_lugar", "provincia_nombre"]
]

from sklearn.model_selection import train_test_split

X_train, X_test, y_train, y_test = train_test_split(
    X,
    y,
    test_size=0.20,
    random_state=42,
    stratify=y
)

# Todas nuestras variables predictoras son categóricas. Vamos a utilizar One-Hot Encoding. Para ello usamos un Pipeline y ColumnTransformer.

from sklearn.compose import ColumnTransformer
from sklearn.preprocessing import OneHotEncoder

columnas_categoricas = [
    "clima_condicion",
    "franja_horaria",
    "tipo_lugar",
    "provincia_nombre"
]

preprocesador = ColumnTransformer(
    transformers=[
        (
            "categoricas",
            OneHotEncoder(handle_unknown="ignore"),   #Puede ocurrir que una categoría aparezca en X_test pero no haya aparecido durante el entrenamiento. En vez de generar un error, el codificador simplemente la ignora.
            columnas_categoricas
        )
    ]
)

"""**Primer modelo: Regresión Logística**"""

# Creamos el pipeline:

from sklearn.pipeline import Pipeline
from sklearn.linear_model import LogisticRegression

modelo = Pipeline([
    ("preprocesamiento", preprocesador),
    ("clasificador", LogisticRegression(
        max_iter=1000
    ))
])

# Y entrenamos
modelo.fit(X_train, y_train)

y_pred = modelo.predict(X_test)

